"""Frond vs the competition -- template rendering throughput (Python).

The gap this fills: benchmark_results.json measures only `json` and `list`, and
carbon_benchmarks.py measures Frond's template category against ITSELF in four
languages. Neither has ever timed Frond against the engines it competes with.

Two things this harness does that a naive template benchmark does not:

1. IT PROVES THE ENGINES DO THE SAME WORK. Every engine renders the same page and the
   output is compared before anything is timed. Whitespace around block tags
   legitimately differs between engines, so the comparison collapses whitespace runs --
   but raw byte lengths are printed too, so a suspicious difference stays visible
   instead of being normalised away. A mismatch ABORTS. Timing engines that emit
   different HTML is the most common way a template benchmark lies.

2. IT MEASURES STEADY STATE, NOT COMPILATION. Each engine's template is compiled ONCE
   outside the clock, then rendered repeatedly, which is what a real app does per
   request. Compiling inside the loop would report Jinja2 as roughly an order of
   magnitude slower than it is -- a strawman, not a benchmark.

Fairness rule: each engine uses ITS OWN idiomatic construct rather than being forced
into Frond's syntax. Jinja2 has no `number_format` filter, so it gets `format('%.2f')`,
which is a builtin and therefore the fast path. The equivalence gate is what proves the
comparison is honest -- not identical template bytes.

Competitor libraries are installed on demand into the active environment, matching
compare_frameworks.py. They are NEVER framework dependencies; the Tina4 core stays
zero-dependency.

Run: uv run python benchmarks/bench_templates.py
"""

import importlib
import os
import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

REPORT_PATH = Path(__file__).resolve().parent / "template_comparison.json"

# Timed runs continue until this much wall-clock has elapsed...
MIN_SECONDS = 0.25
# ...but never fewer than this many iterations, however fast the engine.
MIN_ITERATIONS = 200


def _ensure_installed():
    """Install Jinja2 and Mako if they are not already importable."""
    needed = []
    for pkg, import_name in [("jinja2", "jinja2"), ("mako", "mako")]:
        try:
            importlib.import_module(import_name)
        except ImportError:
            needed.append(pkg)
    if not needed:
        return
    print(f"  Installing missing packages: {', '.join(needed)} ...")
    # `python -m pip` fails outright in a uv-managed venv, which is what this repo
    # uses -- uv does not install pip into the environment. Try pip, then fall back
    # to `uv pip`, and only give up (with the real reason) if both are unavailable.
    for cmd in (
        [sys.executable, "-m", "pip", "install", "--quiet", *needed],
        ["uv", "pip", "install", "--quiet", *needed],
    ):
        try:
            subprocess.check_call(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            print("  Done.\n")
            return
        except (subprocess.CalledProcessError, FileNotFoundError):
            continue
    print(f"  Could not install {', '.join(needed)} with either pip or uv pip.")
    print(f"  Install them yourself and re-run: uv pip install {' '.join(needed)}\n")
    sys.exit(1)


def page_data():
    """20 rows is a realistic list page, not a microbenchmark of one hole."""
    return {
        "title": "Benchmark Page",
        "heading": "Product List",
        "items": [{"name": f"Product {i}", "price": i * 9.99} for i in range(20)],
        "show_footer": True,
        "footer_text": "Generated by Tina4 Frond for the template throughput comparison.",
    }


def normalise(html: str) -> str:
    """Collapse whitespace runs so block-tag indentation differences between engines do
    not register as output differences. Everything else must match exactly."""
    return " ".join(html.split())


def measure(render):
    """Time a render callable: p50 and mean ops/sec.

    Batched for the same reason the carbon suite batches -- a render is fast enough that
    two perf_counter() reads are a measurable fraction of the work, and a mean alone
    hides a fat tail. Setup is outside the clock; only the render is timed.
    """
    # Warm-up is a LOOP and runs twice: one pass still pays cold costs (imports,
    # lazily-built caches, first compile), and reading a single cold op collapses the
    # batch size to 1, defeating the amortisation.
    calibration_ops = 64
    one = 1e-9
    for _ in range(2):
        t0 = time.perf_counter()
        for _ in range(calibration_ops):
            render()
        one = max((time.perf_counter() - t0) / calibration_ops, 1e-9)

    batch = min(max(int(5e-5 / one), 1), 10_000)

    batches = []
    iterations = 0
    start = time.perf_counter()
    while True:
        b0 = time.perf_counter()
        for _ in range(batch):
            render()
        batches.append((time.perf_counter() - b0) / batch)
        iterations += batch
        if (time.perf_counter() - start) >= MIN_SECONDS and iterations >= MIN_ITERATIONS:
            break

    batches.sort()
    mid = len(batches) // 2
    p50 = batches[mid] if len(batches) % 2 else (batches[mid - 1] + batches[mid]) / 2
    mean = sum(batches) / len(batches)
    return {
        "p50_ops_sec": 1 / p50 if p50 > 0 else 0,
        "mean_ops_sec": 1 / mean if mean > 0 else 0,
        "iterations": iterations,
        "batches": len(batches),
    }


FROND_SOURCE = """<!DOCTYPE html>
<html>
<head><title>{{ title }}</title></head>
<body>
<h1>{{ heading }}</h1>
<ul>
{% for item in items %}
<li class="{{ loop.index is even ? 'even' : 'odd' }}">{{ loop.index }}. {{ item.name|upper }} - ${{ item.price|number_format(2) }}</li>
{% endfor %}
</ul>
{% if show_footer %}
<footer>{{ footer_text }}</footer>
{% endif %}
</body>
</html>"""

# Jinja2: same {{ }} / {% %} family, but its own idioms -- an inline `if` expression
# instead of the ternary, and `format` (a builtin) instead of number_format.
JINJA_SOURCE = """<!DOCTYPE html>
<html>
<head><title>{{ title }}</title></head>
<body>
<h1>{{ heading }}</h1>
<ul>
{% for item in items %}
<li class="{{ 'even' if loop.index is even else 'odd' }}">{{ loop.index }}. {{ item.name|upper }} - ${{ '%.2f'|format(item.price) }}</li>
{% endfor %}
</ul>
{% if show_footer %}
<footer>{{ footer_text }}</footer>
{% endif %}
</body>
</html>"""

MAKO_SOURCE = """<!DOCTYPE html>
<html>
<head><title>${title}</title></head>
<body>
<h1>${heading}</h1>
<ul>
% for i, item in enumerate(items, 1):
<li class="${'even' if i % 2 == 0 else 'odd'}">${i}. ${item['name'].upper()} - $${'%.2f' % item['price']}</li>
% endfor
</ul>
% if show_footer:
<footer>${footer_text}</footer>
% endif
</body>
</html>"""


def main():
    _ensure_installed()

    from jinja2 import Environment as JinjaEnvironment
    from mako.template import Template as MakoTemplate

    from tina4_python.frond import Frond

    tmp = tempfile.mkdtemp()
    (Path(tmp) / "page.twig").write_text(FROND_SOURCE)

    data = page_data()
    engines = {}

    # --- Frond (Tina4, zero dependencies) -----------------------------------------
    frond = Frond(template_dir=tmp)
    engines["Frond (Tina4)"] = lambda: frond.render("page.twig", data)

    # --- Jinja2 --------------------------------------------------------------------
    # Compiled to Python bytecode ONCE, outside the clock. Compiling per render would
    # be a strawman.
    jinja_template = JinjaEnvironment().from_string(JINJA_SOURCE)
    engines["Jinja2"] = lambda: jinja_template.render(**data)

    # --- Mako ----------------------------------------------------------------------
    mako_template = MakoTemplate(MAKO_SOURCE)
    engines["Mako"] = lambda: mako_template.render(**data)

    print("\nTina4 Frond vs the competition -- template rendering "
          f"(Python {sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro})\n")
    print("  Output equivalence gate")
    print("  " + "-" * 72)

    rendered = {name: fn() for name, fn in engines.items()}

    reference = None
    reference_name = ""
    mismatch = False
    for name, html in rendered.items():
        norm = normalise(html)
        if reference is None:
            reference, reference_name = norm, name
            print(f"    {name:<22} {len(html):6d} bytes raw  (reference)")
            continue
        same = norm == reference
        print(f"    {name:<22} {len(html):6d} bytes raw  {'IDENTICAL' if same else 'MISMATCH'}")
        if not same:
            mismatch = True
            # Show where they diverge. A silent normalise-and-move-on is how a
            # benchmark ends up comparing engines that render different pages.
            at = next(
                (i for i, (a, b) in enumerate(zip(norm, reference)) if a != b),
                min(len(norm), len(reference)),
            )
            print(f"      first difference at char {at}:")
            print(f"        {reference_name}: ...{reference[max(0, at - 40):at + 50]}...")
            print(f"        {name}: ...{norm[max(0, at - 40):at + 50]}...")

    if mismatch:
        print("\n  ABORTED: the engines do not render the same page, so any timing below")
        print("  would be comparing different work. Fix the templates first.\n")
        sys.exit(1)

    print("\n  All engines render the same page. Timing is meaningful.\n")

    # Prove Frond ran its FASTEST path, not a fallback. Without this the comparison is
    # dismissable with "you benchmarked the interpreter". Frond has an AOT compiler
    # (frond/compiler.py, ADR-0001) that turns the AST into a render function and
    # returns None -- falling back to walking the AST -- for any construct it does not
    # handle. Which path ran is invisible from outside, and a number measured on the
    # fallback means something completely different.
    compiled_fns = getattr(frond, "_compiled_fn", {}) or {}
    aot_active = any(v is not None for v in compiled_fns.values())
    debug_mode = os.environ.get("TINA4_DEBUG", "").lower() == "true"
    print("  Frond configuration (so the number cannot be dismissed)")
    print("  " + "-" * 72)
    print(f"    AOT compiler (frond.compiler)  "
          f"{'ACTIVE - compiled render function' if aot_active else 'FALLBACK - walking the AST'}")
    print(f"    TINA4_DEBUG                    "
          f"{'true (dev path)' if debug_mode else 'not true (production: template cache active)'}")
    if not aot_active:
        print("\n    WARNING: Frond is on the interpreter fallback, so this measures the SLOW")
        print("    path. Find which construct the compiler rejected before quoting a ratio.")
    print()

    print(f"  {'Engine':<22} {'p50 ops/sec':>13} {'mean ops/sec':>13}   samples")
    print("  " + "-" * 72)

    results = {}
    for name, fn in engines.items():
        m = measure(fn)
        results[name] = m
        print(f"  {name:<22} {m['p50_ops_sec']:>13,.0f} {m['mean_ops_sec']:>13,.0f}"
              f"   {m['iterations']:,}x{m['batches']}")

    frond_p50 = results["Frond (Tina4)"]["p50_ops_sec"]
    print("\n  Relative to Frond (p50):")
    for name, m in results.items():
        if name == "Frond (Tina4)":
            continue
        ratio = frond_p50 / m["p50_ops_sec"] if m["p50_ops_sec"] > 0 else float("inf")
        faster = "faster" if ratio >= 1 else "SLOWER"
        print(f"    Frond is {(ratio if ratio >= 1 else 1 / ratio):.2f}x {faster} than {name}")

    REPORT_PATH.write_text(json.dumps({
        "language": "python",
        "runtime": f"Python {sys.version.split()[0]}",
        "page": {"items": 20, "engines": list(engines)},
        "output_equivalence": "verified",
        "results": results,
    }, indent=2) + "\n")
    print(f"\n  Wrote {REPORT_PATH.name}")
    print("\n  Note: steady-state render only. Every engine's template is compiled ONCE")
    print("  outside the clock, matching how an app serves a page. Cold-start compile")
    print("  cost is a separate question and is NOT measured here.\n")


if __name__ == "__main__":
    main()
